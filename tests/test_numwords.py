import pytest

from server.numwords import normalize


@pytest.mark.parametrize("src,want", [
    ("temperature अट्ठानवे point चार", "temperature 98.4"),
    ("वज़न दो दशमलव आठ किलो", "वज़न 2.8 किलो"),
    ("बच्चे का weight ढाई किलो है", "बच्चे का weight 2.5 किलो है"),
    ("साढ़े तीन किलो", "3.5 किलो"),
    ("सवा तीन किलो", "3.25 किलो"),
    ("पौने तीन किलो", "2.75 किलो"),
    ("BP एक सौ बीस बटा अस्सी", "BP 120 बटा 80"),
    ("ID एक शून्य शून्य चार", "ID 1004"),
    ("वज़न अट्ठावन किलो,", "वज़न 58 किलो,"),
    ("IFA गोली तीस दी", "IFA गोली 30 दी"),
    ("पंद्रह दिन बाद", "15 दिन बाद"),
    ("दवा दो", "दवा दो"),          # imperative "give", not a number
    ("IFA गोली दो", "IFA गोली दो"),
    ("गोली दो किलो", "गोली 2 किलो"),
    ("एक बात बताओ", "एक बात बताओ"),
    ("सांस चौंसठ प्रति मिनट", "सांस 64 प्रति मिनट"),
])
def test_normalize(src, want):
    assert normalize(src) == want
